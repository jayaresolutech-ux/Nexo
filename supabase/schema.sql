create table if not exists public.clientes (
    id bigint primary key,
    nome text,
    documento text,
    email text,
    telefone text,
    cidade text,
    limite_credito numeric,
    ativo text,
    criado_em date,
    observacoes text
);

create table if not exists public.fornecedores (
    id bigint primary key,
    nome text,
    documento text,
    email text,
    telefone text,
    cidade text,
    prazo_entrega_dias integer,
    avaliacao numeric,
    ativo text,
    criado_em date
);

create table if not exists public.produtos (
    id bigint primary key,
    sku text,
    nome text,
    categoria text,
    unidade text,
    custo numeric,
    preco numeric,
    estoque_atual numeric,
    estoque_minimo numeric,
    ativo text
);

create table if not exists public.categorias (
    id bigint primary key,
    nome text
);

create table if not exists public.vendas (
    id bigint primary key,
    data date,
    cliente_id bigint,
    cliente text,
    status text,
    desconto numeric,
    total numeric,
    custo_total numeric,
    forma_pagamento text,
    prazo_dias integer,
    observacoes text
);

create table if not exists public.itens_venda (
    id bigint primary key,
    venda_id bigint,
    produto_id bigint,
    produto text,
    quantidade numeric,
    preco_unitario numeric,
    custo_unitario numeric
);

create table if not exists public.compras (
    id bigint primary key,
    data date,
    fornecedor_id bigint,
    fornecedor text,
    nota_fiscal text,
    status text,
    total numeric,
    prazo_dias integer,
    data_recebimento date
);

create table if not exists public.itens_compra (
    id bigint primary key,
    compra_id bigint,
    produto_id bigint,
    produto text,
    quantidade numeric,
    custo_unitario numeric
);

create table if not exists public.movimentos_estoque (
    id bigint primary key,
    data date,
    produto_id bigint,
    produto text,
    tipo text,
    quantidade numeric,
    origem text,
    saldo_apos numeric
);

create table if not exists public.contas_receber (
    id bigint primary key,
    venda_id bigint,
    cliente_id bigint,
    cliente text,
    descricao text,
    emissao date,
    vencimento date,
    valor numeric,
    status text,
    data_pagamento date
);

create table if not exists public.contas_pagar (
    id bigint primary key,
    compra_id bigint,
    fornecedor_id bigint,
    fornecedor text,
    descricao text,
    emissao date,
    vencimento date,
    valor numeric,
    status text,
    data_pagamento date
);

create table if not exists public.parametros (
    id bigint primary key,
    chave text,
    valor text
);

alter table public.clientes enable row level security;
alter table public.fornecedores enable row level security;
alter table public.produtos enable row level security;
alter table public.categorias enable row level security;
alter table public.vendas enable row level security;
alter table public.itens_venda enable row level security;
alter table public.compras enable row level security;
alter table public.itens_compra enable row level security;
alter table public.movimentos_estoque enable row level security;
alter table public.contas_receber enable row level security;
alter table public.contas_pagar enable row level security;
alter table public.parametros enable row level security;

do $$
declare
    table_name text;
begin
    foreach table_name in array array[
        'clientes', 'fornecedores', 'produtos', 'categorias', 'vendas',
        'itens_venda', 'compras', 'itens_compra', 'movimentos_estoque',
        'contas_receber', 'contas_pagar', 'parametros'
    ]
    loop
        if pg_catalog.pg_get_serial_sequence('public.' || table_name, 'id') is null then
            execute format(
                'alter table public.%I alter column id add generated by default as identity',
                table_name
            );
        end if;

        execute format(
            'select pg_catalog.setval('
            'pg_catalog.pg_get_serial_sequence(%L, %L), '
            'coalesce(max(id), 1), max(id) is not null) from public.%I',
            'public.' || table_name,
            'id',
            table_name
        );
    end loop;
end;
$$;

